// Generate src/data/worldGeo.ts: a GeoJSON FeatureCollection of country
// polygons tagged with ISO-3166-1 alpha-2 codes, for runtime projection by the
// rotating globe (d3-geo geoOrthographic). Coordinates are rounded to 1 decimal
// degree (~11km) to keep the committed file small; that's plenty for a small
// globe.
//
// Run once (output is committed); deps are devDependencies only:
//   bun run scripts/gen-worldgeo.mjs
//
// Source: world-atlas countries-110m (coarse, small).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { feature } from "topojson-client";
import topo from "world-atlas/countries-110m.json" assert { type: "json" };
import iso from "i18n-iso-countries";

const fc = feature(topo, topo.objects.countries);

/** Round every coordinate to 1 decimal, recursively through the geometry. */
const roundCoords = (c) =>
  typeof c[0] === "number"
    ? [Math.round(c[0] * 10) / 10, Math.round(c[1] * 10) / 10]
    : c.map(roundCoords);

const features = [];
for (const f of fc.features) {
  const code = iso.numericToAlpha2(String(f.id).padStart(3, "0"));
  if (!code || !f.geometry) continue;
  features.push({
    type: "Feature",
    properties: { code, name: f.properties.name },
    geometry: { type: f.geometry.type, coordinates: roundCoords(f.geometry.coordinates) },
  });
}
features.sort((a, b) => a.properties.code.localeCompare(b.properties.code));

const collection = { type: "FeatureCollection", features };

const header = `// AUTO-GENERATED by scripts/gen-worldgeo.mjs. Do not edit by hand.
// GeoJSON country polygons keyed by ISO-3166-1 alpha-2 (matches the Cloudflare
// Web Analytics country dimension), for runtime projection by the rotating
// globe. Source: world-atlas countries-110m, coordinates rounded to 1 decimal.

import type { FeatureCollection } from "geojson";

export interface CountryProps {
  /** ISO-3166-1 alpha-2 country code. */
  code: string;
  name: string;
}

export const worldGeo = ${JSON.stringify(collection)} as unknown as FeatureCollection<
  GeoJSON.Geometry,
  CountryProps
>;
`;

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "worldGeo.ts");
writeFileSync(out, header);
console.error(`wrote ${features.length} countries -> ${out}`);
