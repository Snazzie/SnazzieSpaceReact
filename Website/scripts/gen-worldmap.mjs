// Generate src/data/worldMap.ts: a pre-projected equirectangular world map,
// one SVG path per country, keyed by ISO-3166-1 alpha-2 (the join key used by
// the Cloudflare Web Analytics country dimension).
//
// Run once (output is committed); deps are devDependencies only and never ship
// to the client:
//   bun run scripts/gen-worldmap.mjs
//
// Source: world-atlas countries-110m (coarse, small) projected with d3-geo.
// Coordinates are rounded to 1 decimal against a 1000x500 viewBox to keep the
// committed file small.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import topo from "world-atlas/countries-110m.json" assert { type: "json" };
import iso from "i18n-iso-countries";

const WIDTH = 1000;
const HEIGHT = 500;

const fc = feature(topo, topo.objects.countries);
const projection = geoEquirectangular().fitSize([WIDTH, HEIGHT], { type: "Sphere" });
const path = geoPath(projection);

/** Round every number in an SVG path `d` to 1 decimal place. */
const round = (d) => d.replace(/-?\d+\.\d+/g, (m) => String(Math.round(parseFloat(m) * 10) / 10));

const rows = [];
for (const f of fc.features) {
  const numeric = String(f.id).padStart(3, "0");
  const code = iso.numericToAlpha2(numeric);
  if (!code) continue;
  const d = path(f);
  if (!d) continue;
  rows.push({ code, name: f.properties.name, d: round(d) });
}
rows.sort((a, b) => a.code.localeCompare(b.code));

const header = `// AUTO-GENERATED by scripts/gen-worldmap.mjs. Do not edit by hand.
// Equirectangular world map projected to a ${WIDTH}x${HEIGHT} viewBox, one path
// per country keyed by ISO-3166-1 alpha-2 (matches the Cloudflare Web Analytics
// country dimension). Source: world-atlas countries-110m.

export interface CountryShape {
  /** ISO-3166-1 alpha-2 country code. */
  code: string;
  name: string;
  /** SVG path \`d\` in the ${WIDTH}x${HEIGHT} viewBox. */
  d: string;
}

export const WORLD_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";

export const worldMap: CountryShape[] = ${JSON.stringify(rows, null, 0)};
`;

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "worldMap.ts");
writeFileSync(out, header);
console.error(`wrote ${rows.length} countries -> ${out}`);
